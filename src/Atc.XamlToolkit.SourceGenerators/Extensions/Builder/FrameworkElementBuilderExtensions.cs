internal static class FrameworkElementBuilderExtensions
{
    public static void GenerateStart(
        this FrameworkElementBuilder builder,
        FrameworkElementToGenerate frameworkElementToGenerate)
    {
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("#nullable enable");

        var xamlPlatform = frameworkElementToGenerate.XamlPlatform;

        var namespaces = CommandBuilderBase.GetCommandUsings(xamlPlatform, frameworkElementToGenerate.RelayCommandsToGenerate);

        // Only WPF supports UpdateSourceTrigger
        if (xamlPlatform == XamlPlatform.Wpf &&
            !frameworkElementToGenerate.DependencyPropertiesToGenerate.IsEmpty &&
            frameworkElementToGenerate.DependencyPropertiesToGenerate.Any(x => x.DefaultUpdateSourceTrigger is not null))
        {
            namespaces.Add("System.Windows.Data");
        }

        var properties = frameworkElementToGenerate.AttachedPropertiesToGenerate
            .Cast<BaseFrameworkElementPropertyToGenerate>()
            .Concat(frameworkElementToGenerate.DependencyPropertiesToGenerate)
            .ToList();

        if (properties.Count > 0 ||
            (xamlPlatform == XamlPlatform.Wpf && !frameworkElementToGenerate.RoutedEventsToGenerate.IsEmpty))
        {
            // The platform's property system types (DependencyProperty, StyledProperty, ...)
            namespaces.Add(xamlPlatform switch
            {
                XamlPlatform.WinUI => "Microsoft.UI.Xaml",
                XamlPlatform.Avalonia => "Avalonia",
                _ => "System.Windows",
            });
        }

        if (frameworkElementToGenerate.DefaultStyleKey is { } defaultStyleKey)
        {
            if (xamlPlatform == XamlPlatform.Wpf)
            {
                // FrameworkPropertyMetadata
                namespaces.Add("System.Windows");
            }

            // The style type is written by its simple name
            namespaces.AddRange(defaultStyleKey.RequiredNamespaces);
        }

        foreach (var templatePart in frameworkElementToGenerate.TemplatePartsToGenerate)
        {
            // The type of the part is written by its simple name
            namespaces.AddRange(templatePart.RequiredNamespaces);
        }

        foreach (var property in properties)
        {
            // The property type is written by its simple name
            namespaces.AddRange(property.RequiredNamespaces);

            if (!string.IsNullOrEmpty(property.Category) ||
                !string.IsNullOrEmpty(property.Description))
            {
                // [Category] and [Description]
                namespaces.Add("System.ComponentModel");
            }
        }

        builder.AppendUsings(namespaces, frameworkElementToGenerate.NamespaceName);

        builder.AppendTypeStart(frameworkElementToGenerate);
    }

    public static void GenerateDefaultStyleKey(
        this FrameworkElementBuilder builder,
        FrameworkElementToGenerate frameworkElementToGenerate)
    {
        if (frameworkElementToGenerate.DefaultStyleKey is not { } defaultStyleKey)
        {
            return;
        }

        var ownerType = frameworkElementToGenerate.ClassName + frameworkElementToGenerate.TypeParameterList;
        var styleType = defaultStyleKey.StyleTypeName ?? ownerType;

        builder.AppendLineBeforeMember();

        if (frameworkElementToGenerate.XamlPlatform == XamlPlatform.Avalonia)
        {
            builder.AppendLine("/// <inheritdoc />");
            builder.AppendLine($"protected override global::System.Type StyleKeyOverride => typeof({styleType});");
            return;
        }

        if (defaultStyleKey.HasOwnStaticConstructor)
        {
            // A class can only have one static constructor, so the hand-written one has to call this.
            builder.AppendLine("/// <summary>");
            builder.AppendLine(defaultStyleKey.StyleTypeName is null
                ? "/// Makes this type its own default style key. Call it from the static constructor."
                : $"/// Makes <see cref=\"{styleType.Replace('<', '{').Replace('>', '}')}\"/> the default style key of this type. Call it from the static constructor.");
            builder.AppendLine("/// </summary>");
            builder.AppendLine($"private static void {NameConstants.OverrideDefaultStyleKey}()");
            builder.IncreaseIndent();
            builder.AppendLine("=> DefaultStyleKeyProperty.OverrideMetadata(");
            builder.IncreaseIndent();
            builder.AppendLine($"typeof({ownerType}),");
            builder.AppendLine($"new FrameworkPropertyMetadata(typeof({styleType})));");
            builder.DecreaseIndent();
            builder.DecreaseIndent();
            return;
        }

        builder.AppendLine($"static {frameworkElementToGenerate.ClassName}()");
        builder.AppendLine("{");
        builder.IncreaseIndent();
        builder.AppendLine("DefaultStyleKeyProperty.OverrideMetadata(");
        builder.IncreaseIndent();
        builder.AppendLine($"typeof({ownerType}),");
        builder.AppendLine($"new FrameworkPropertyMetadata(typeof({styleType})));");
        builder.DecreaseIndent();
        builder.DecreaseIndent();
        builder.AppendLine("}");
    }

    public static void GenerateTemplateParts(
        this FrameworkElementBuilder builder,
        FrameworkElementToGenerate frameworkElementToGenerate)
    {
        var templateParts = frameworkElementToGenerate.TemplatePartsToGenerate;
        if (templateParts.IsEmpty)
        {
            return;
        }

        var isAvalonia = frameworkElementToGenerate.XamlPlatform == XamlPlatform.Avalonia;

        builder.AppendLineBeforeMember();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Assigns the template parts to their fields. Call it from <c>OnApplyTemplate</c>.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine(isAvalonia
            ? $"private void {NameConstants.ResolveTemplateParts}(global::Avalonia.Controls.Primitives.TemplateAppliedEventArgs e)"
            : $"private void {NameConstants.ResolveTemplateParts}()");
        builder.AppendLine("{");
        builder.IncreaseIndent();

        foreach (var templatePart in templateParts)
        {
            var lookup = isAvalonia
                ? $"e.NameScope.Find<{templatePart.TypeName}>({templatePart.PartNameExpression})"
                : $"GetTemplateChild({templatePart.PartNameExpression}) as {templatePart.TypeName}";

            if (templatePart.IsRequired)
            {
                var partName = templatePart.PartNameText ?? $"{{{templatePart.PartNameExpression}}}";
                var message = $"Template part '{partName}' of type '{templatePart.TypeName}' was not found in the template of '{frameworkElementToGenerate.ClassName}'.";
                var messageLiteral = templatePart.PartNameText is null
                    ? "$" + SymbolDisplay.FormatLiteral(message, quote: true)
                    : SymbolDisplay.FormatLiteral(message, quote: true);

                builder.AppendLine($"{templatePart.FieldName} = {lookup}");
                builder.IncreaseIndent();
                builder.AppendLine($"?? throw new global::System.InvalidOperationException({messageLiteral});");
                builder.DecreaseIndent();
            }
            else if (templatePart.IsFieldNullable)
            {
                builder.AppendLine($"{templatePart.FieldName} = {lookup};");
            }
            else
            {
                // The field is declared non-nullable although the part is optional: keep that choice.
                builder.AppendLine(isAvalonia
                    ? $"{templatePart.FieldName} = {lookup}!;"
                    : $"{templatePart.FieldName} = ({lookup})!;");
            }
        }

        builder.DecreaseIndent();
        builder.AppendLine("}");
    }

    public static void GenerateAttachedProperties(
        this FrameworkElementBuilder builder,
        XamlPlatform xamlPlatform,
        IEnumerable<AttachedPropertyToGenerate>? attachedPropertiesToGenerate)
    {
        if (attachedPropertiesToGenerate is null)
        {
            return;
        }

        foreach (var propertyToGenerate in attachedPropertiesToGenerate)
        {
            GenerateAttachedProperty(builder, propertyToGenerate, xamlPlatform);
        }
    }

    public static void GenerateDependencyProperties(
        this FrameworkElementBuilder builder,
        XamlPlatform xamlPlatform,
        IEnumerable<DependencyPropertyToGenerate>? dependencyPropertiesToGenerate)
    {
        if (dependencyPropertiesToGenerate is null)
        {
            return;
        }

        var propertiesToGenerate = dependencyPropertiesToGenerate.ToList();

        foreach (var propertyToGenerate in propertiesToGenerate)
        {
            GenerateDependencyProperty(builder, propertyToGenerate, xamlPlatform);
        }

        // For Avalonia, generate static constructor to register callbacks
        if (xamlPlatform == XamlPlatform.Avalonia && propertiesToGenerate.Count > 0)
        {
            var propertiesWithCallbacks = propertiesToGenerate
                .Where(p => !string.IsNullOrEmpty(p.PropertyChangedCallback))
                .ToList();

            if (propertiesWithCallbacks.Count > 0)
            {
                var className = propertiesToGenerate[0].OwnerType;
                GenerateAvaloniaStaticConstructor(builder, className, propertiesWithCallbacks);
            }
        }
    }

    public static void GenerateRoutedEvents(
        this FrameworkElementBuilder builder,
        IEnumerable<RoutedEventToGenerate>? routedEventToGenerates)
    {
        if (routedEventToGenerates is null)
        {
            return;
        }

        foreach (var routedEventToGenerate in routedEventToGenerates)
        {
            GenerateRoutedEvent(builder, routedEventToGenerate);
        }
    }

    private static void GenerateAttachedProperty(
        FrameworkElementBuilder builder,
        AttachedPropertyToGenerate p,
        XamlPlatform xamlPlatform)
    {
        GenerateDependencyPropertyHeader(builder, p, isAttached: true, xamlPlatform);
        GenerateDependencyPropertyBody(builder, p, xamlPlatform);

        if (xamlPlatform == XamlPlatform.Avalonia &&
            !string.IsNullOrEmpty(p.PropertyChangedCallback))
        {
            // Avalonia has no callback parameter on RegisterAttached. A static field initializer
            // subscribes instead of a static constructor, so the class can still declare its own.
            // The handler runs for every AvaloniaObject the property is attached to.
            builder.AppendLine();
            builder.AppendLine($"private static readonly System.IDisposable {p.Name.EnsureFirstCharacterToLower()}PropertyChangedSubscription = {p.Name}Property.Changed.AddClassHandler<AvaloniaObject>({p.PropertyChangedCallback});");
        }

        GenerateClrAttachedMethods(builder, p, xamlPlatform);
        GeneratePartialHook(builder, p, isAttached: true, xamlPlatform);
    }

    private static void GenerateDependencyProperty(
        FrameworkElementBuilder builder,
        DependencyPropertyToGenerate p,
        XamlPlatform xamlPlatform)
    {
        GenerateDependencyPropertyHeader(builder, p, isAttached: false, xamlPlatform);
        GenerateDependencyPropertyBody(builder, p, xamlPlatform);
        GenerateClrDependencyProperty(builder, p, xamlPlatform);
        GeneratePartialHook(builder, p, isAttached: false, xamlPlatform);
    }

    // Emits the static callback that is registered with the property system, and the typed
    // partial method it calls. An attached property has no owner instance, so its hook is
    // static and receives the object the property is attached to.
    private static void GeneratePartialHook(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        bool isAttached,
        XamlPlatform xamlPlatform)
    {
        if (!p.GeneratePartialHooks)
        {
            return;
        }

        var isAvalonia = xamlPlatform == XamlPlatform.Avalonia;
        var hookName = $"On{p.Name}Changed";

        // The object the callback receives: the owner for a styled property on Avalonia
        // (AddClassHandler<Owner>), otherwise the platform's base object.
        string senderType;
        if (!isAvalonia)
        {
            senderType = "DependencyObject";
        }
        else if (isAttached)
        {
            senderType = "AvaloniaObject";
        }
        else
        {
            senderType = p.OwnerType;
        }

        var senderName = isAvalonia && !isAttached ? "sender" : "d";
        var eventArgsType = isAvalonia ? "AvaloniaPropertyChangedEventArgs" : "DependencyPropertyChangedEventArgs";

        var oldValue = isAvalonia ? $"e.GetOldValue<{p.Type}>()" : $"({p.Type})e.OldValue";
        var newValue = isAvalonia ? $"e.GetNewValue<{p.Type}>()" : $"({p.Type})e.NewValue";

        string hookCall;
        if (isAttached)
        {
            hookCall = $"{hookName}({senderName}, {oldValue}, {newValue})";
        }
        else if (isAvalonia)
        {
            hookCall = $"{senderName}.{hookName}({oldValue}, {newValue})";
        }
        else
        {
            hookCall = $"(({p.OwnerType}){senderName}).{hookName}({oldValue}, {newValue})";
        }

        builder.AppendLine();
        builder.AppendLine($"private static void {p.PropertyChangedCallback}(");
        builder.IncreaseIndent();
        builder.AppendLine($"{senderType} {senderName},");
        builder.AppendLine($"{eventArgsType} e)");

        if (string.IsNullOrEmpty(p.UserPropertyChangedCallback))
        {
            builder.AppendLine($"=> {hookCall};");
            builder.DecreaseIndent();
        }
        else
        {
            builder.DecreaseIndent();
            builder.AppendLine("{");
            builder.IncreaseIndent();
            builder.AppendLine($"{p.UserPropertyChangedCallback}({senderName}, e);");
            builder.AppendLine($"{hookCall};");
            builder.DecreaseIndent();
            builder.AppendLine("}");
        }

        builder.AppendLine();
        builder.AppendLine(isAttached
            ? $"static partial void {hookName}({senderType} {senderName}, {p.Type} oldValue, {p.Type} newValue);"
            : $"partial void {hookName}({p.Type} oldValue, {p.Type} newValue);");
    }

    private static void GenerateDependencyPropertyHeader(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        bool isAttached,
        XamlPlatform xamlPlatform)
    {
        var registerMethod = isAttached
            ? NameConstants.RegisterAttached
            : NameConstants.Register;

        // Platform-specific DependencyProperty type
        var dependencyPropertyType = xamlPlatform switch
        {
            XamlPlatform.WinUI => "Microsoft.UI.Xaml.DependencyProperty",
            XamlPlatform.Avalonia when isAttached => "Avalonia.AvaloniaProperty",
            XamlPlatform.Avalonia => $"StyledProperty<{p.TypeForTypeOf}>",
            _ => "DependencyProperty", // WPF
        };

        builder.AppendLineBeforeMember();

        if (!p.DocumentationComments.IsEmpty || p.GenerateDocumentation)
        {
            builder.AppendSummary(GetPropertyIdentifierSummary(p, isAttached, xamlPlatform));
        }

        // Avalonia uses generic type parameters, WPF/WinUI use typeof() parameters
        if (xamlPlatform == XamlPlatform.Avalonia)
        {
            var genericParams = isAttached
                ? $"<{p.OwnerType.RemoveNullableSuffix()}, AvaloniaObject, {p.TypeForTypeOf}>"
                : $"<{p.OwnerType.RemoveNullableSuffix()}, {p.TypeForTypeOf}>";

            // For non-attached properties (StyledProperty), use AvaloniaProperty.Register, not StyledProperty<T>.Register
            const string registrationClass = "Avalonia.AvaloniaProperty";

            builder.AppendLine(
                p.UseNewKeyword
                    ? $"public static new readonly {dependencyPropertyType} {p.Name}Property = {registrationClass}.{registerMethod}{genericParams}("
                    : $"public static readonly {dependencyPropertyType} {p.Name}Property = {registrationClass}.{registerMethod}{genericParams}(");
        }
        else
        {
            builder.AppendLine(
                p.UseNewKeyword
                    ? $"public static new readonly {dependencyPropertyType} {p.Name}Property = {dependencyPropertyType}.{registerMethod}("
                    : $"public static readonly {dependencyPropertyType} {p.Name}Property = {dependencyPropertyType}.{registerMethod}(");
        }

        builder.IncreaseIndent();

        // For Avalonia, only add comma if there's a default value (checked in body generation)
        // For WPF/WinUI, always add comma as there are more parameters
        var hasDefaultValue = p.DefaultValue is not null && !"null".Equals(p.DefaultValue);
        var needsComma = xamlPlatform != XamlPlatform.Avalonia || hasDefaultValue;

        if (isAttached || p.IsOwnerTypeStatic)
        {
            builder.AppendLine(needsComma ? $"\"{p.Name}\"," : $"\"{p.Name}\"");
        }
        else
        {
            builder.AppendLine(needsComma ? $"{p.Name.EnsureNameofContent()}," : $"{p.Name.EnsureNameofContent()}");
        }

        // Skip typeof() lines for Avalonia (it uses generics instead)
        if (xamlPlatform != XamlPlatform.Avalonia)
        {
            builder.AppendLine($"typeof({p.TypeForTypeOf}),");
        }
    }

    private static string GetPropertyIdentifierSummary(
        BaseFrameworkElementPropertyToGenerate p,
        bool isAttached,
        XamlPlatform xamlPlatform)
    {
        // Attached properties and properties on a static owner only have Get/Set methods,
        // so there is no {Name} member for a cref to point at.
        if (isAttached || p.IsOwnerTypeStatic)
        {
            return $"Identifies the {p.Name} attached property.";
        }

        return xamlPlatform == XamlPlatform.Avalonia
            ? $"Identifies the <see cref=\"{p.Name}\"/> styled property."
            : $"Identifies the <see cref=\"{p.Name}\"/> dependency property.";
    }

    private static void GenerateDependencyPropertyBody(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        XamlPlatform xamlPlatform)
    {
        // Avalonia has a completely different registration API
        if (xamlPlatform == XamlPlatform.Avalonia)
        {
            GenerateAvaloniaPropertyBody(builder, p);
            return;
        }

        // WinUI doesn't support ValidateValueCallback, CoerceValueCallback, Flags, DefaultUpdateSourceTrigger, IsAnimationProhibited
        var isWpf = xamlPlatform == XamlPlatform.Wpf;

        if (p.HasAnyMetadata)
        {
            builder.AppendLine($"typeof({p.OwnerType.RemoveNullableSuffix()}),");

            if (string.IsNullOrEmpty(p.Flags) &&
                string.IsNullOrEmpty(p.PropertyChangedCallback) &&
                string.IsNullOrEmpty(p.CoerceValueCallback) &&
                string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger) &&
                p.IsAnimationProhibited is null)
            {
                if (isWpf && p.HasAnyValidateValueCallback)
                {
                    if (p.DefaultValue is not null && !"null".Equals(p.DefaultValue))
                    {
                        builder.AppendLine($"new PropertyMetadata(defaultValue: {p.DefaultValue}),");
                    }
                    else
                    {
                        builder.AppendLine("new PropertyMetadata(defaultValue: null),");
                    }

                    builder.DecreaseIndent();
                    builder.AppendLine($"validateValueCallback: {p.ValidateValueCallback});");
                }
                else
                {
                    if (p.DefaultValue is not null && !"null".Equals(p.DefaultValue))
                    {
                        builder.AppendLine($"new PropertyMetadata(defaultValue: {p.DefaultValue}));");
                    }
                    else
                    {
                        builder.AppendLine("new PropertyMetadata());");
                    }

                    builder.DecreaseIndent();
                }
            }
            else
            {
                if (string.IsNullOrEmpty(p.Flags) &&
                    string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger) &&
                    p.IsAnimationProhibited is null)
                {
                    if (isWpf && p.HasAnyValidateValueCallback)
                    {
                        GeneratePropertyMetadataExtended(builder, p, endWithComma: true);
                        builder.DecreaseIndent();
                        builder.AppendLine($"validateValueCallback: {p.ValidateValueCallback});");
                    }
                    else
                    {
                        GeneratePropertyMetadataExtended(builder, p, endWithComma: false);
                        builder.DecreaseIndent();
                    }
                }
                else
                {
                    // FrameworkPropertyMetadata is WPF-only
                    if (isWpf)
                    {
                        if (p.HasAnyValidateValueCallback)
                        {
                            GenerateFrameworkPropertyMetadata(builder, p, endWithComma: true);
                            builder.DecreaseIndent();
                            builder.AppendLine($"validateValueCallback: {p.ValidateValueCallback});");
                        }
                        else
                        {
                            GenerateFrameworkPropertyMetadata(builder, p, endWithComma: false);
                            builder.DecreaseIndent();
                        }
                    }
                    else
                    {
                        // For WinUI, fall back to simple PropertyMetadata
                        GeneratePropertyMetadataExtended(builder, p, endWithComma: false);
                        builder.DecreaseIndent();
                    }
                }

                builder.DecreaseIndent();
            }
        }
        else
        {
            switch (isWpf)
            {
                case true when p.HasAnyValidateValueCallback:
                    builder.AppendLine($"typeof({p.OwnerType.RemoveNullableSuffix()}),");
                    builder.DecreaseIndent();
                    builder.AppendLine($"validateValueCallback: {p.ValidateValueCallback});");
                    break;
                case false:
                    // WinUI requires PropertyMetadata parameter even if empty
                    builder.AppendLine($"typeof({p.OwnerType.RemoveNullableSuffix()}),");
                    builder.AppendLine("new PropertyMetadata(default));");
                    builder.DecreaseIndent();
                    break;
                default:
                    // WPF without metadata
                    builder.AppendLine($"typeof({p.OwnerType.RemoveNullableSuffix()}));");
                    builder.DecreaseIndent();
                    break;
            }
        }
    }

    private static void GeneratePropertyMetadataExtended(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        bool endWithComma)
    {
        builder.AppendLine("new PropertyMetadata(");
        builder.IncreaseIndent();
        if (p.DefaultValue is not null && !"null".Equals(p.DefaultValue))
        {
            builder.AppendLine($"defaultValue: {p.DefaultValue},");
        }
        else
        {
            builder.AppendLine("defaultValue: null,");
        }

        if (string.IsNullOrEmpty(p.PropertyChangedCallback))
        {
            // PropertyMetadata has no (defaultValue, coerceValueCallback) constructor
            builder.AppendLine("propertyChangedCallback: null,");
            builder.AppendLine(
                endWithComma
                    ? $"coerceValueCallback: {p.CoerceValueCallback}),"
                    : $"coerceValueCallback: {p.CoerceValueCallback}));");
        }
        else if (string.IsNullOrEmpty(p.CoerceValueCallback))
        {
            builder.AppendLine(
                endWithComma
                    ? $"propertyChangedCallback: {p.PropertyChangedCallback}),"
                    : $"propertyChangedCallback: {p.PropertyChangedCallback}));");
        }
        else
        {
            builder.AppendLine($"propertyChangedCallback: {p.PropertyChangedCallback},");
            builder.AppendLine(
                endWithComma
                    ? $"coerceValueCallback: {p.CoerceValueCallback}),"
                    : $"coerceValueCallback: {p.CoerceValueCallback}));");
        }
    }

    private static void GenerateFrameworkPropertyMetadata(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        bool endWithComma)
    {
        if (RequiresFullFrameworkPropertyMetadataConstructor(p))
        {
            GenerateFullFrameworkPropertyMetadata(builder, p, endWithComma);
            return;
        }

        builder.AppendLine("new FrameworkPropertyMetadata(");
        builder.IncreaseIndent();
        if (p.DefaultValue is not null && !"null".Equals(p.DefaultValue))
        {
            builder.AppendLine($"defaultValue: {p.DefaultValue},");
        }
        else
        {
            builder.AppendLine("defaultValue: null,");
        }

        if (!string.IsNullOrEmpty(p.PropertyChangedCallback))
        {
            builder.AppendLine($"propertyChangedCallback: {p.PropertyChangedCallback},");
        }

        if (!string.IsNullOrEmpty(p.CoerceValueCallback))
        {
            builder.AppendLine($"coerceValueCallback: {p.CoerceValueCallback},");
        }

        var hasAddedLine = false;
        if (!string.IsNullOrEmpty(p.Flags))
        {
            builder.Append($"flags: {p.Flags}");
            hasAddedLine = true;
        }

        if (!string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger))
        {
            if (hasAddedLine)
            {
                builder.AppendLine(",");
            }

            if (string.IsNullOrEmpty(p.CoerceValueCallback))
            {
                builder.AppendLine("coerceValueCallback: null,");
            }

            if (!p.IsAnimationProhibited.HasValue)
            {
                builder.AppendLine("isAnimationProhibited: false,");
            }

            builder.Append($"defaultUpdateSourceTrigger: {p.DefaultUpdateSourceTrigger}");
        }

        if (p.IsAnimationProhibited.HasValue)
        {
            if (hasAddedLine)
            {
                builder.AppendLine(",");
            }

            if (string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger) &&
                string.IsNullOrEmpty(p.CoerceValueCallback))
            {
                builder.AppendLine("coerceValueCallback: null,");
            }

            var isAnimationProhibited = p.IsAnimationProhibited
                .Value
                .ToString()
                .ToLowerInvariant();
            builder.Append($"isAnimationProhibited: {isAnimationProhibited}");
        }

        builder.AppendLine(
            endWithComma
                ? "),"
                : "));");
    }

    /// <summary>
    /// The coerce callback, IsAnimationProhibited and DefaultUpdateSourceTrigger are only available
    /// on constructors that also take flags and propertyChangedCallback.
    /// </summary>
    private static bool RequiresFullFrameworkPropertyMetadataConstructor(
        BaseFrameworkElementPropertyToGenerate p)
        => (!string.IsNullOrEmpty(p.CoerceValueCallback) ||
            !string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger) ||
            p.IsAnimationProhibited.HasValue) &&
           (string.IsNullOrEmpty(p.Flags) ||
            string.IsNullOrEmpty(p.PropertyChangedCallback));

    private static void GenerateFullFrameworkPropertyMetadata(
        FrameworkElementBuilder builder,
        BaseFrameworkElementPropertyToGenerate p,
        bool endWithComma)
    {
        var defaultValue = p.DefaultValue is not null && !"null".Equals(p.DefaultValue)
            ? p.DefaultValue
            : "null";

        var arguments = new List<string>
        {
            $"defaultValue: {defaultValue}",
            $"flags: {(string.IsNullOrEmpty(p.Flags) ? "FrameworkPropertyMetadataOptions.None" : p.Flags)}",
            $"propertyChangedCallback: {(string.IsNullOrEmpty(p.PropertyChangedCallback) ? "null" : p.PropertyChangedCallback)}",
            $"coerceValueCallback: {(string.IsNullOrEmpty(p.CoerceValueCallback) ? "null" : p.CoerceValueCallback)}",
        };

        if (p.IsAnimationProhibited.HasValue ||
            !string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger))
        {
            var isAnimationProhibited = p.IsAnimationProhibited.GetValueOrDefault()
                .ToString()
                .ToLowerInvariant();
            arguments.Add($"isAnimationProhibited: {isAnimationProhibited}");
        }

        if (!string.IsNullOrEmpty(p.DefaultUpdateSourceTrigger))
        {
            arguments.Add($"defaultUpdateSourceTrigger: {p.DefaultUpdateSourceTrigger}");
        }

        builder.AppendLine("new FrameworkPropertyMetadata(");
        builder.IncreaseIndent();
        for (var i = 0; i < arguments.Count - 1; i++)
        {
            builder.AppendLine($"{arguments[i]},");
        }

        builder.AppendLine(
            endWithComma
                ? $"{arguments[arguments.Count - 1]}),"
                : $"{arguments[arguments.Count - 1]}));");
    }

    private static void GenerateClrDependencyProperty(
        FrameworkElementBuilder builder,
        DependencyPropertyToGenerate p,
        XamlPlatform xamlPlatform)
    {
        var elementType = xamlPlatform switch
        {
            XamlPlatform.Avalonia => NameConstants.AvaloniaObject,
            _ => NameConstants.DependencyObject, // WPF and WinUI
        };

        builder.AppendLine();

        if (p.IsOwnerTypeStatic)
        {
            builder.AppendDocumentation(p.DocumentationComments, p.GenerateDocumentation, $"Gets the {p.Name} attached property value.");

            if (!string.IsNullOrEmpty(p.Category))
            {
                builder.AppendLine($"[Category(\"{p.Category}\")]");
            }

            if (!string.IsNullOrEmpty(p.Description))
            {
                builder.AppendLine($"[Description(\"Get: {p.Description}\")]");
            }

            builder.AppendLine($"public static {p.Type} Get{p.Name}({elementType} element)");
            builder.IncreaseIndent();

            // For Avalonia with non-nullable reference/value types, add null-forgiving operator
            if (xamlPlatform == XamlPlatform.Avalonia &&
                !p.Type.EndsWith("?", StringComparison.Ordinal))
            {
                builder.AppendLine($"=> ({p.Type})element.GetValue({p.Name}Property)!;");
            }
            else
            {
                builder.AppendLine($"=> ({p.Type})element.GetValue({p.Name}Property);");
            }

            builder.DecreaseIndent();

            builder.AppendLine();

            builder.AppendDocumentation(p.DocumentationComments, p.GenerateDocumentation, $"Sets the {p.Name} attached property value.");

            if (!string.IsNullOrEmpty(p.Category))
            {
                builder.AppendLine($"[Category(\"{p.Category}\")]");
            }

            if (!string.IsNullOrEmpty(p.Description))
            {
                builder.AppendLine($"[Description(\"Set: {p.Description}\")]");
            }

            builder.AppendLine($"public static void Set{p.Name}({elementType} element, {p.Type} value)");
            builder.IncreaseIndent();
            builder.AppendLine(
                p.Type.StartsWith("bool", StringComparison.Ordinal) && xamlPlatform != XamlPlatform.Avalonia
                    ? $"=> element?.SetValue({p.Name}Property, Atc.XamlToolkit.BooleanBoxes.Box(value));"
                    : $"=> element?.SetValue({p.Name}Property, value);");
            builder.DecreaseIndent();
        }
        else
        {
            builder.AppendDocumentation(p.DocumentationComments, p.GenerateDocumentation, $"Gets or sets the {p.Name}.");

            if (!string.IsNullOrEmpty(p.Category))
            {
                builder.AppendLine($"[Category(\"{p.Category}\")]");
            }

            if (!string.IsNullOrEmpty(p.Description))
            {
                builder.AppendLine($"[Description(\"{p.Description}\")]");
            }

            builder.AppendLine(
                p.UseNewKeyword
                    ? $"public new {p.Type} {p.Name}"
                    : $"public {p.Type} {p.Name}");
            builder.AppendLine("{");
            builder.IncreaseIndent();

            // For Avalonia with non-nullable reference/value types, add null-forgiving operator
            if (xamlPlatform == XamlPlatform.Avalonia &&
                !p.Type.EndsWith("?", StringComparison.Ordinal))
            {
                builder.AppendLine($"get => ({p.Type})GetValue({p.Name}Property)!;");
            }
            else
            {
                builder.AppendLine($"get => ({p.Type})GetValue({p.Name}Property);");
            }

            if (!p.IsReadOnly)
            {
                var setter = p.SetterAccessModifier.Length == 0 ? "set" : $"{p.SetterAccessModifier} set";

                builder.AppendLine(
                    p.Type.StartsWith("bool", StringComparison.Ordinal) && xamlPlatform != XamlPlatform.Avalonia
                        ? $"{setter} => SetValue({p.Name}Property, Atc.XamlToolkit.BooleanBoxes.Box(value));"
                        : $"{setter} => SetValue({p.Name}Property, value);");
            }

            builder.DecreaseIndent();
            builder.AppendLine("}");
        }
    }

    private static void GenerateClrAttachedMethods(
        FrameworkElementBuilder builder,
        AttachedPropertyToGenerate p,
        XamlPlatform xamlPlatform)
    {
        var elementType = xamlPlatform switch
        {
            XamlPlatform.Avalonia => NameConstants.AvaloniaObject,
            _ => NameConstants.DependencyObject, // WPF and WinUI
        };

        builder.AppendLine();

        builder.AppendDocumentation(p.DocumentationComments, p.GenerateDocumentation, $"Gets the {p.Name} attached property value.");

        if (!string.IsNullOrEmpty(p.Category))
        {
            builder.AppendLine($"[Category(\"{p.Category}\")]");
        }

        if (!string.IsNullOrEmpty(p.Description))
        {
            builder.AppendLine($"[Description(\"Get: {p.Description}\")]");
        }

        builder.AppendLine($"public static {p.Type} Get{p.Name}({elementType} element)");
        builder.IncreaseIndent();

        // For Avalonia with non-nullable reference/value types, add null-forgiving operator
        if (xamlPlatform == XamlPlatform.Avalonia &&
            !p.Type.EndsWith("?", StringComparison.Ordinal))
        {
            builder.AppendLine($"=> ({p.Type})element.GetValue({p.Name}Property)!;");
        }
        else
        {
            builder.AppendLine($"=> ({p.Type})element.GetValue({p.Name}Property);");
        }

        if (!p.IsReadOnly)
        {
            builder.DecreaseIndent();

            builder.AppendLine();

            builder.AppendDocumentation(p.DocumentationComments, p.GenerateDocumentation, $"Sets the {p.Name} attached property value.");

            if (!string.IsNullOrEmpty(p.Category))
            {
                builder.AppendLine($"[Category(\"{p.Category}\")]");
