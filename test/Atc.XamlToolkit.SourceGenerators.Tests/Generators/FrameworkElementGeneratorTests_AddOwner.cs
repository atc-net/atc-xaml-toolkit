namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

[SuppressMessage("Design", "MA0048:File name must match type name", Justification = "OK.")]
public sealed partial class FrameworkElementGeneratorTests
{
    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_SharesTheExistingProperty()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TokenBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(ComboBox))]
                private double maxDropDownHeight;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable
            using System.Windows;

            namespace TestNamespace;

            public partial class TokenBox
            {
                public static readonly DependencyProperty MaxDropDownHeightProperty = ComboBox.MaxDropDownHeightProperty.AddOwner(
                    typeof(TokenBox));

                public double MaxDropDownHeight
                {
                    get => (double)GetValue(MaxDropDownHeightProperty);
                    set => SetValue(MaxDropDownHeightProperty, value);
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_BoolWithoutDefaultValue_KeepsTheSharedDefault()
    {
        // No metadata is passed, so the default value of the shared property is not replaced.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class NumericBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(TextBoxBase))]
                private bool isReadOnly;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("IsReadOnlyProperty = TextBoxBase.IsReadOnlyProperty.AddOwner(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("typeof(NumericBox));", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("Metadata", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_WithCallbackOnly_PassesMetadataWithoutADefaultValue()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class PathIcon : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(Path), PropertyChangedCallback = nameof(OnDataChanged))]
                private Geometry data;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains(
            """
                public static readonly DependencyProperty DataProperty = Path.DataProperty.AddOwner(
                    typeof(PathIcon),
                    new FrameworkPropertyMetadata(propertyChangedCallback: OnDataChanged));
            """.EnsureEnvironmentNewLines(),
            generatedCode.EnsureEnvironmentNewLines(),
            StringComparison.Ordinal);
        Assert.DoesNotContain("defaultValue", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_WithHooks_PassesBothGeneratedCallbacks()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TokenBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(ComboBox), GeneratePartialHooks = true, GenerateCoerceHook = true)]
                private double maxDropDownHeight;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("new FrameworkPropertyMetadata(propertyChangedCallback: OnMaxDropDownHeightPropertyChangedCallback, coerceValueCallback: CoerceMaxDropDownHeightPropertyCallback));", generatedCode, StringComparison.Ordinal);
        Assert.Contains("partial void OnMaxDropDownHeightChanged(double oldValue, double newValue);", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private partial double CoerceMaxDropDownHeight(double value);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_WithDefaultValueAndFlags_PassesFrameworkMetadata()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class NumericBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(TextBoxBase), DefaultValue = false, Flags = FrameworkPropertyMetadataOptions.Inherits, PropertyChangedCallback = nameof(OnIsReadOnlyPropertyChanged))]
                private bool isReadOnly;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("IsReadOnlyProperty = TextBoxBase.IsReadOnlyProperty.AddOwner(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("typeof(NumericBox),", generatedCode, StringComparison.Ordinal);
        Assert.Contains("new FrameworkPropertyMetadata(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("defaultValue: Atc.XamlToolkit.BooleanBoxes.FalseBox,", generatedCode, StringComparison.Ordinal);
        Assert.Contains("propertyChangedCallback: OnIsReadOnlyPropertyChanged,", generatedCode, StringComparison.Ordinal);
        Assert.Contains("flags: FrameworkPropertyMetadataOptions.Inherits));", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_WithOnlyADefaultValue_UsesFrameworkMetadata()
    {
        // The metadata passed to AddOwner must be of the shared property's metadata type or a
        // type derived from it; FrameworkPropertyMetadata fits every built-in property.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TokenBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(ComboBox), DefaultValue = 250d)]
                private double maxDropDownHeight;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("new FrameworkPropertyMetadata(defaultValue: 250d));", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AddOwnerOf_Wpf_IgnoresValidateValueCallback()
    {
        // Validation belongs to the registration of the shared property; AddOwner cannot change it.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TokenBox : UserControl
            {
                [DependencyProperty(AddOwnerOf = typeof(ComboBox), ValidateValueCallback = nameof(IsValid))]
                private double maxDropDownHeight;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("typeof(TokenBox));", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("validateValueCallback", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_WithoutAddOwnerOf_IsRegisteredAsBefore()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TokenBox : UserControl
            {
                [DependencyProperty]
                private double maxDropDownHeight;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("MaxDropDownHeightProperty = DependencyProperty.Register(", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("AddOwner", generatedCode, StringComparison.Ordinal);
    }
}