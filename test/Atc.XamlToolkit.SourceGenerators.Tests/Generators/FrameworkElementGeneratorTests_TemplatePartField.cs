namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

[SuppressMessage("Design", "MA0048:File name must match type name", Justification = "OK.")]
public sealed partial class FrameworkElementGeneratorTests
{
    [Fact]
    public void TemplatePartField_Wpf_GeneratesClassAttributesAndResolveMethod()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : Control
            {
                [TemplatePartField("PART_Overlay")]
                private Border? overlayBorder;

                [TemplatePartField("PART_CloseButton")]
                private Button? closeButton;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            [global::System.Windows.TemplatePart(Name = "PART_Overlay", Type = typeof(Border))]
            [global::System.Windows.TemplatePart(Name = "PART_CloseButton", Type = typeof(Button))]
            public partial class MyControl
            {
                /// <summary>
                /// Assigns the template parts to their fields. Call it from <c>OnApplyTemplate</c>.
                /// </summary>
                private void ResolveTemplateParts()
                {
                    overlayBorder = GetTemplateChild("PART_Overlay") as Border;
                    closeButton = GetTemplateChild("PART_CloseButton") as Button;
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void TemplatePartField_Wpf_RequiredPart_ThrowsWhenMissing()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : Control
            {
                [TemplatePartField("PART_Overlay", IsRequired = true)]
                private Border overlayBorder = null!;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            [global::System.Windows.TemplatePart(Name = "PART_Overlay", Type = typeof(Border))]
            public partial class MyControl
            {
                /// <summary>
                /// Assigns the template parts to their fields. Call it from <c>OnApplyTemplate</c>.
                /// </summary>
                private void ResolveTemplateParts()
                {
                    overlayBorder = GetTemplateChild("PART_Overlay") as Border
                        ?? throw new global::System.InvalidOperationException("Template part 'PART_Overlay' of type 'Border' was not found in the template of 'MyControl'.");
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void TemplatePartField_Wpf_NonNullableFieldThatIsNotRequired_KeepsTheDeclaredNullability()
    {
        // The field is declared non-nullable although the part is optional. That is the
        // author's choice; the generated assignment must not add a nullable warning to it.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : Control
            {
                [TemplatePartField("PART_Overlay")]
                private Border overlayBorder = null!;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("overlayBorder = (GetTemplateChild(\"PART_Overlay\") as Border)!;", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void TemplatePartField_Wpf_PartAlreadyDeclaredOnTheClass_IsNotDeclaredTwice()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            [TemplatePart(Name = "PART_Overlay", Type = typeof(Border))]
            public partial class MyControl : Control
            {
                [TemplatePartField("PART_Overlay")]
                private Border? overlayBorder;

                [TemplatePartField("PART_CloseButton")]
                private Button? closeButton;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.DoesNotContain("TemplatePart(Name = \"PART_Overlay\"", generatedCode, StringComparison.Ordinal);
        Assert.Contains("[global::System.Windows.TemplatePart(Name = \"PART_CloseButton\", Type = typeof(Button))]", generatedCode, StringComparison.Ordinal);
        Assert.Contains("overlayBorder = GetTemplateChild(\"PART_Overlay\") as Border;", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void TemplatePartField_Wpf_TogetherWithDependencyProperty_GeneratesBoth()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : Control
            {
                [DependencyProperty]
                private bool isActive;

                [TemplatePartField("PART_Overlay")]
                private Border? overlayBorder;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("public static readonly DependencyProperty IsActiveProperty", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private void ResolveTemplateParts()", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void TemplatePartField_WinUI_UsesTheWinUIAttribute()
    {
        // The stub type makes the generator treat the compilation as a WinUI project.
        const string inputCode =
            """
            namespace Microsoft.UI.Xaml
            {
                public class DependencyObject { }
            }

            namespace TestNamespace
            {
                public partial class MyControl : Control
                {
                    [TemplatePartField("PART_Overlay")]
                    private Border? overlayBorder;
                }
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("[global::Microsoft.UI.Xaml.TemplatePart(Name = \"PART_Overlay\", Type = typeof(Border))]", generatedCode, StringComparison.Ordinal);
        Assert.Contains("overlayBorder = GetTemplateChild(\"PART_Overlay\") as Border;", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void TemplatePartField_Avalonia_GeneratesCodeThatCompiles()
    {
        const string inputCode =
            """
            using Atc.XamlToolkit.Controls.Attributes;
            using Avalonia.Controls;
            using Avalonia.Controls.Primitives;

            namespace TestNamespace;

            public partial class MyControl : TemplatedControl
            {
                private const string PartCloseButton = "PART_CloseButton";

                [TemplatePartField("PART_Overlay")]
                private Border? overlayBorder;

                [TemplatePartField(PartCloseButton, IsRequired = true)]
                private Button closeButton = null!;

                public bool HasParts => overlayBorder is not null && closeButton is not null;

                protected override void OnApplyTemplate(TemplateAppliedEventArgs e)
                {
                    base.OnApplyTemplate(e);
                    ResolveTemplateParts(e);
                }
            }
            """;

        AssertCompilesWithAllGeneratorsWithoutGlobalUsings(inputCode);

        var generatedCode = string.Join(
            Environment.NewLine,
            GetSourcesGeneratedForAvaloniaConsumer(inputCode));

        Assert.Contains("[global::Avalonia.Controls.Metadata.TemplatePart(\"PART_Overlay\", typeof(Border))]", generatedCode, StringComparison.Ordinal);
        Assert.Contains("[global::Avalonia.Controls.Metadata.TemplatePart(\"PART_CloseButton\", typeof(Button))]", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private void ResolveTemplateParts(global::Avalonia.Controls.Primitives.TemplateAppliedEventArgs e)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("overlayBorder = e.NameScope.Find<Border>(\"PART_Overlay\");", generatedCode, StringComparison.Ordinal);
    }
}