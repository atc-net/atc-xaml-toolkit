namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

[SuppressMessage("Design", "MA0048:File name must match type name", Justification = "OK.")]
public sealed partial class ViewModelGeneratorTests
{
    [Fact]
    public void ObservableProperty_IsRequired_True_EmitsRequiredKeyword()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TestViewModel : ViewModelBase
            {
                [ObservableProperty(IsRequired = true)]
                private string name;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            public partial class TestViewModel
            {
                public required string Name
                {
                    get => name;
                    set
                    {
                        if (name == value)
                        {
                            return;
                        }

                        name = value;
                        RaisePropertyChanged(nameof(Name));
                    }
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<ViewModelGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void ObservableProperty_IsRequired_False_OmitsRequiredKeyword()
    {
        // Negative test: the existing default-off behaviour must produce
        // exactly the legacy output (no `required` keyword anywhere).
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TestViewModel : ViewModelBase
            {
                [ObservableProperty]
                private string name;
            }
            """;

        var generatorResult = RunGenerator<ViewModelGenerator>(inputCode);

        var generated = generatorResult.GeneratorResult.GeneratedSources[0]
            .SourceText
            .ToString();

        generated.Should().NotContain("required");
    }

    [Fact]
    public void ObservableProperty_IsRequired_True_ComposesWithGeneratePartialHooks()
    {
        // Sanity check: required + partial-hooks compose without drama —
        // verifies neither feature steps on the other.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TestViewModel : ViewModelBase
            {
                [ObservableProperty(IsRequired = true, GeneratePartialHooks = true)]
                private string name;
            }
            """;

        var generatorResult = RunGenerator<ViewModelGenerator>(inputCode);

        var generated = generatorResult.GeneratorResult.GeneratedSources[0]
            .SourceText
            .ToString();

        generated.Should().Contain("public required string Name");
        generated.Should().Contain("partial void OnNameChanging(string value);");
        generated.Should().Contain("partial void OnNameChanged(string value);");
        generated.Should().Contain("OnNameChanging(value);");
        generated.Should().Contain("OnNameChanged(value);");
    }
}