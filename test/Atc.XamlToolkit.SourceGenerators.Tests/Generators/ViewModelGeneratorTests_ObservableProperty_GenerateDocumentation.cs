// ReSharper disable StringLiteralTypo
namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

public class ViewModelGeneratorTests_ObservableProperty_GenerateDocumentation : GeneratorTestBase
{
    [Fact]
    public void GenerateDocumentation_True_NoFieldDocs_EmitsDefaultSummary()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TestViewModel : ViewModelBase
            {
                [ObservableProperty(GenerateDocumentation = true)]
                private string firstName = string.Empty;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            public partial class TestViewModel
            {
                /// <summary>
                /// Gets or sets the FirstName.
                /// </summary>
                public string FirstName
                {
                    get => firstName;
                    set
                    {
                        if (firstName == value)
                        {
                            return;
                        }

                        firstName = value;
                        RaisePropertyChanged(nameof(FirstName));
                    }
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<ViewModelGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void GenerateDocumentation_False_NoFieldDocs_EmitsNoSummary()
    {
        // Pinning the default-off behaviour: existing snapshots stay byte-identical.
        const string inputCode =
