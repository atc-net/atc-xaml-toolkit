namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

[SuppressMessage("Design", "MA0048:File name must match type name", Justification = "OK.")]
public sealed partial class FrameworkElementGeneratorTests
{
    private static string GenerateFrameworkElementCode(string inputCode)
        => Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources)
            .SourceText
            .ToString()
            .EnsureEnvironmentNewLines();

    [Fact]
    public void AttachedProperty_TargetType_Wpf_IsUsedForTheAccessorParameter()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public static partial class CheckBoxHelper
            {
                [AttachedProperty(TargetType = typeof(UIElement))]
                private static CornerRadius checkCornerRadius;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("public static CornerRadius GetCheckCornerRadius(UIElement element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("public static void SetCheckCornerRadius(UIElement element, CornerRadius value)", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("DependencyObject element", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_WithoutTargetType_Wpf_TakesADependencyObject()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public static partial class CheckBoxHelper
            {
                [AttachedProperty]
                private static CornerRadius checkCornerRadius;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("public static CornerRadius GetCheckCornerRadius(DependencyObject element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("public static void SetCheckCornerRadius(DependencyObject element, CornerRadius value)", generatedCode, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("Internal", "internal")]
    [InlineData("Private", "private")]
    [InlineData("Protected", "protected")]
    public void AttachedProperty_AccessModifier_Wpf_AppliesToTheFieldAndTheAccessors(
        string enumValue,
        string modifier)
    {
        var inputCode =
            $$"""
            namespace TestNamespace;

            public partial class DataGridFilter
            {
                [AttachedProperty(AccessModifier = PropertyAccessModifier.{{enumValue}})]
                private static bool isFiltered;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains($"    {modifier} static readonly DependencyProperty IsFilteredProperty = DependencyProperty.RegisterAttached(", generatedCode, StringComparison.Ordinal);
        Assert.Contains($"    {modifier} static bool GetIsFiltered(DependencyObject element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains($"    {modifier} static void SetIsFiltered(DependencyObject element, bool value)", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("public", generatedCode.Replace("public partial class", string.Empty, StringComparison.Ordinal), StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_AccessModifierAndSetterAccessModifier_Wpf_SetterModifierWinsForTheSetMethod()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public static partial class DataGridFilter
            {
                [AttachedProperty(AccessModifier = PropertyAccessModifier.Internal, SetterAccessModifier = PropertyAccessModifier.Private)]
                private static bool isFiltered;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("internal static bool GetIsFiltered(DependencyObject element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private static void SetIsFiltered(DependencyObject element, bool value)", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_GenerateClrAccessorsFalse_Wpf_GeneratesOnlyTheField()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public static partial class DataGridFilter
            {
                [AttachedProperty(AccessModifier = PropertyAccessModifier.Private, GenerateClrAccessors = false)]
                private static DataGridFilterState state;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable
            using System.Windows;

            namespace TestNamespace;

            public static partial class DataGridFilter
            {
                private static readonly DependencyProperty StateProperty = DependencyProperty.RegisterAttached(
                    "State",
                    typeof(DataGridFilterState),
                    typeof(DataGridFilter));
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void DependencyProperty_AccessModifier_Wpf_AppliesToTheFieldAndTheProperty()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class ZoomBox : UserControl
            {
                [DependencyProperty(AccessModifier = PropertyAccessModifier.Private)]
                private double internalViewportZoom;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("    private static readonly DependencyProperty InternalViewportZoomProperty = DependencyProperty.Register(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("    private double InternalViewportZoom", generatedCode, StringComparison.Ordinal);
        Assert.Contains("new PropertyMetadata(defaultValue: 0d));", generatedCode, StringComparison.Ordinal);
        Assert.Contains("        set => SetValue(InternalViewportZoomProperty, value);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_AccessModifierEqualToSetterAccessModifier_Wpf_DoesNotRepeatTheModifierOnTheSetter()
    {
        // 'private double X { get; private set; }' does not compile: an accessor modifier must
        // be more restrictive than the property.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class ZoomBox : UserControl
            {
                [DependencyProperty(AccessModifier = PropertyAccessModifier.Internal, SetterAccessModifier = PropertyAccessModifier.Internal)]
                private double viewportZoom;

                [DependencyProperty(AccessModifier = PropertyAccessModifier.Internal, SetterAccessModifier = PropertyAccessModifier.Private)]
                private double contentZoom;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("    internal double ViewportZoom", generatedCode, StringComparison.Ordinal);
        Assert.Contains("        set => SetValue(ViewportZoomProperty, value);", generatedCode, StringComparison.Ordinal);
        Assert.Contains("    internal double ContentZoom", generatedCode, StringComparison.Ordinal);
        Assert.Contains("        private set => SetValue(ContentZoomProperty, value);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_GenerateClrAccessorsFalse_Wpf_GeneratesOnlyTheField()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class ZoomBox : UserControl
            {
                [DependencyProperty(GenerateClrAccessors = false)]
                private double viewportZoom;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("public static readonly DependencyProperty ViewportZoomProperty = DependencyProperty.Register(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("\"ViewportZoom\",", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("nameof(", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("GetValue", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("SetValue", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_IsReadOnly_WithAccessModifier_Wpf_AppliesToTheIdentifierTakenFromTheKey()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class ZoomBox : UserControl
            {
                [DependencyProperty(IsReadOnly = true, AccessModifier = PropertyAccessModifier.Internal)]
                private double viewportZoom;
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("    private static readonly DependencyPropertyKey ViewportZoomPropertyKey = DependencyProperty.RegisterReadOnly(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("    internal static readonly DependencyProperty ViewportZoomProperty = ViewportZoomPropertyKey.DependencyProperty;", generatedCode, StringComparison.Ordinal);
        Assert.Contains("    internal double ViewportZoom", generatedCode, StringComparison.Ordinal);
        Assert.Contains("        private set => SetValue(ViewportZoomPropertyKey, value);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_TargetTypeAndAccessModifier_WinUI_AreApplied()
    {
        const string inputCode =
            """
            namespace Microsoft.UI.Xaml
            {
                public class DependencyObject
                {
                }

                public class UIElement : DependencyObject
                {
                }
            }

            namespace TestNamespace
            {
                using Microsoft.UI.Xaml;

                public static partial class CheckBoxHelper
                {
                    [AttachedProperty(TargetType = typeof(UIElement), AccessModifier = PropertyAccessModifier.Internal)]
                    private static double cornerSize;

                    [AttachedProperty(AccessModifier = PropertyAccessModifier.Private, GenerateClrAccessors = false)]
                    private static string state;
                }
            }
            """;

        var generatedCode = GenerateFrameworkElementCode(inputCode);

        Assert.Contains("internal static readonly Microsoft.UI.Xaml.DependencyProperty CornerSizeProperty = Microsoft.UI.Xaml.DependencyProperty.RegisterAttached(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("internal static double GetCornerSize(UIElement element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("internal static void SetCornerSize(UIElement element, double value)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private static readonly Microsoft.UI.Xaml.DependencyProperty StateProperty = Microsoft.UI.Xaml.DependencyProperty.RegisterAttached(", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("GetState", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_AccessModifierAndGenerateClrAccessors_WithResolvedAttributes_Avalonia_GeneratesCodeThatCompiles()
    {
        const string inputCode =
            """
            using Atc.XamlToolkit;
            using Atc.XamlToolkit.Controls.Attributes;
            using Avalonia;

            namespace TestNamespace;

            public partial class FilterBehavior : AvaloniaObject
            {
                [AttachedProperty(AccessModifier = PropertyAccessModifier.Internal)]
                private static bool isFiltered;

                [AttachedProperty(AccessModifier = PropertyAccessModifier.Private, GenerateClrAccessors = false)]
                private static int hits;

                public static int Hit(AvaloniaObject element)
                {
                    SetIsFiltered(element, true);
                    element.SetValue(HitsProperty, (int)element.GetValue(HitsProperty)! + 1);
                    return (int)element.GetValue(HitsProperty)!;
                }
            }
            """;

        AssertCompilesWithAllGeneratorsWithoutGlobalUsings(inputCode);

        var generatedCode = string.Join(
            Environment.NewLine,
            GetSourcesGeneratedForAvaloniaConsumer(inputCode));

        Assert.Contains("internal static bool GetIsFiltered(AvaloniaObject element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("internal static void SetIsFiltered(AvaloniaObject element, bool value)", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("GetHits", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AccessModifierAndGenerateClrAccessors_WithResolvedAttributes_Avalonia_GeneratesCodeThatCompiles()
    {
        const string inputCode =
            """
            using Atc.XamlToolkit;
            using Atc.XamlToolkit.Controls.Attributes;
            using Avalonia.Controls;

            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                [StyledProperty(AccessModifier = PropertyAccessModifier.Internal)]
                private int total;

                [StyledProperty(AccessModifier = PropertyAccessModifier.Private, GenerateClrAccessors = false)]
                private int hidden;

                public void Increase()
                {
                    Total++;
                    SetValue(HiddenProperty, GetValue(HiddenProperty) + 1);
                }
            }
            """;

        AssertCompilesWithAllGeneratorsWithoutGlobalUsings(inputCode);

        var generatedCode = string.Join(
            Environment.NewLine,
            GetSourcesGeneratedForAvaloniaConsumer(inputCode));

        Assert.Contains("internal static readonly StyledProperty<int> TotalProperty", generatedCode, StringComparison.Ordinal);
        Assert.Contains("internal int Total", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private static readonly StyledProperty<int> HiddenProperty", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("int Hidden", generatedCode, StringComparison.Ordinal);
    }
}