namespace Atc.XamlToolkit.SourceGenerators.Tests.Generators;

[SuppressMessage("Design", "MA0048:File name must match type name", Justification = "OK.")]
public sealed partial class FrameworkElementGeneratorTests
{
    [Fact]
    public void DependencyProperty_IsReadOnly_Wpf_GeneratesAPropertyKey()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                [DependencyProperty(IsReadOnly = true)]
                private string summaryText;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable
            using System.Windows;

            namespace TestNamespace;

            public partial class MyControl
            {
                private static readonly DependencyPropertyKey SummaryTextPropertyKey = DependencyProperty.RegisterReadOnly(
                    nameof(SummaryText),
                    typeof(string),
                    typeof(MyControl),
                    new PropertyMetadata());

                public static readonly DependencyProperty SummaryTextProperty = SummaryTextPropertyKey.DependencyProperty;

                public string SummaryText
                {
                    get => (string)GetValue(SummaryTextProperty);
                    private set => SetValue(SummaryTextPropertyKey, value);
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void DependencyProperty_IsReadOnly_Wpf_WithDefaultValueAndSetterAccessModifier()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                [DependencyProperty(IsReadOnly = true, DefaultValue = 3, SetterAccessModifier = PropertyAccessModifier.Internal)]
                private int selectedCount;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("private static readonly DependencyPropertyKey SelectedCountPropertyKey = DependencyProperty.RegisterReadOnly(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("new PropertyMetadata(defaultValue: 3));", generatedCode, StringComparison.Ordinal);
        Assert.Contains("public static readonly DependencyProperty SelectedCountProperty = SelectedCountPropertyKey.DependencyProperty;", generatedCode, StringComparison.Ordinal);
        Assert.Contains("internal set => SetValue(SelectedCountPropertyKey, value);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_IsReadOnly_Wpf_WithOnlyAValidateCallback_StillPassesMetadata()
    {
        // RegisterReadOnly has no overload without metadata.
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                [DependencyProperty(IsReadOnly = true, ValidateValueCallback = nameof(IsValidText))]
                private string summaryText;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains(
            """
                    typeof(MyControl),
                    new PropertyMetadata(),
            """.EnsureEnvironmentNewLines(),
            generatedCode.EnsureEnvironmentNewLines(),
            StringComparison.Ordinal);
        Assert.Contains("validateValueCallback: IsValidText);", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void AttachedProperty_IsReadOnly_Wpf_GeneratesAPropertyKeyAndANonPublicSetMethod()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public static partial class DataGridFilter
            {
                [AttachedProperty(IsReadOnly = true)]
                private static bool isFiltered;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("private static readonly DependencyPropertyKey IsFilteredPropertyKey = DependencyProperty.RegisterAttachedReadOnly(", generatedCode, StringComparison.Ordinal);
        Assert.Contains("public static readonly DependencyProperty IsFilteredProperty = IsFilteredPropertyKey.DependencyProperty;", generatedCode, StringComparison.Ordinal);
        Assert.Contains("public static bool GetIsFiltered(DependencyObject element)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("private static void SetIsFiltered(DependencyObject element, bool value)", generatedCode, StringComparison.Ordinal);
        Assert.Contains("=> element?.SetValue(IsFilteredPropertyKey, Atc.XamlToolkit.BooleanBoxes.Box(value));", generatedCode, StringComparison.Ordinal);
    }

    [Fact]
    public void DependencyProperty_WithoutIsReadOnly_IsRegisteredAsBefore()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                [DependencyProperty]
                private string summaryText;
            }
            """;

        var generatedCode = Assert.Single(RunGenerator<FrameworkElementGenerator>(inputCode).GeneratorResult.GeneratedSources).SourceText.ToString();

        Assert.Contains("public static readonly DependencyProperty SummaryTextProperty = DependencyProperty.Register(", generatedCode, StringComparison.Ordinal);
        Assert.DoesNotContain("PropertyKey", generatedCode, StringComparison.Ordinal);
        Assert.Contains("set => SetValue(SummaryTextProperty, value);", generatedCode, StringComparison.Ordinal);
    }
}