    [Fact]
    public void RoutedEvent_WithDocumentationComments_CopiesDocs()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class CustomButton : Button
            {
                /// <summary>
                /// Occurs when the button is tapped.
                /// </summary>
                [RoutedEvent(RoutingStrategy.Bubble)]
                private static readonly RoutedEvent tap;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            public partial class CustomButton
            {
                /// <summary>
                /// Identifies the <see cref="Tap"/> routed event.
                /// </summary>
                public static readonly RoutedEvent TapEvent = EventManager.RegisterRoutedEvent(
                    name: nameof(Tap),
                    routingStrategy: RoutingStrategy.Bubble,
                    handlerType: typeof(RoutedEventHandler),
                    ownerType: typeof(CustomButton));

                /// <summary>
                /// Occurs when the button is tapped.
                /// </summary>
                public event RoutedEventHandler Tap
                {
                    add => AddHandler(TapEvent, value);
                    remove => RemoveHandler(TapEvent, value);
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

    [Fact]
    public void RelayCommand_WithDocumentationComments_CopiesDocsWithoutMethodOnlyElements()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class TestControl : UserControl
            {
                /// <summary>
                /// Opens the <paramref name="item"/>.
                /// </summary>
                /// <param name="item">
                /// The item to open.
                /// </param>
                /// <remarks>Does nothing when the item is empty.</remarks>
                [RelayCommand]
                public void Open(string item)
                {
                }
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable
            using Atc.XamlToolkit.Command;

            namespace TestNamespace;

            public partial class TestControl
            {
                private IRelayCommand<string>? openCommand;

                /// <summary>
                /// Opens the <c>item</c>.
                /// </summary>
                /// <remarks>Does nothing when the item is empty.</remarks>
                public IRelayCommand<string> OpenCommand => openCommand ??= new RelayCommand<string>(Open);
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

