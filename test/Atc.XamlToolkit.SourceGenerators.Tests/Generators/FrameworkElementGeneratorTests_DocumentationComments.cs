    [Fact]
    public void DependencyProperty_Field_WithDocumentationComments_CopiesDocs()
    {
        const string inputCode =
            """
            namespace TestNamespace;

            public partial class MyControl : UserControl
            {
                /// <summary>
                /// Gets or sets a value indicating whether the pane is open.
                /// </summary>
                /// <remarks>
                /// The pane is closed by default.
                /// </remarks>
                [DependencyProperty]
                private bool isOpen;
            }
            """;

        const string expectedCode =
            """
            // <auto-generated>
            #nullable enable

            namespace TestNamespace;

            public partial class MyControl
            {
                /// <summary>
                /// Identifies the <see cref="IsOpen"/> dependency property.
                /// </summary>
                public static readonly DependencyProperty IsOpenProperty = DependencyProperty.Register(
                    nameof(IsOpen),
                    typeof(bool),
                    typeof(MyControl),
                    new PropertyMetadata(defaultValue: Atc.XamlToolkit.BooleanBoxes.FalseBox));

                /// <summary>
                /// Gets or sets a value indicating whether the pane is open.
                /// </summary>
                /// <remarks>
                /// The pane is closed by default.
                /// </remarks>
                public bool IsOpen
                {
                    get => (bool)GetValue(IsOpenProperty);
                    set => SetValue(IsOpenProperty, Atc.XamlToolkit.BooleanBoxes.Box(value));
                }
            }

            #nullable disable
            """;

        var generatorResult = RunGenerator<FrameworkElementGenerator>(inputCode);

        AssertGeneratorRunResultAsEqual(expectedCode, generatorResult);
    }

